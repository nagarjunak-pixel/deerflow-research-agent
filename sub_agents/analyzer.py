"""Analyzer sub-agent — synthesis and report generation."""

from datetime import datetime


class AnalyzerAgent:
    """Synthesizes research findings into structured reports."""

    def analyze(
        self,
        topic: str,
        plan: dict,
        findings: list[dict],
        depth: str = "standard",
    ) -> dict:
        """
        Analyze findings and generate a research report.

        Args:
            topic: Research topic.
            plan: Research plan with sub-tasks.
            findings: List of search findings.
            depth: Research depth level.

        Returns:
            Report dict with markdown content and metadata.
        """
        date_str = datetime.now().strftime("%Y-%m-%d")

        # Build markdown report
        sections = []

        # Title and metadata
        sections.append(f"# Research Report: {topic}")
        sections.append(f"")
        sections.append(f"**Date:** {date_str}")
        sections.append(f"**Depth:** {depth}")
        sections.append(f"**Sources:** {len(findings)}")
        sections.append(f"**Sub-tasks:** {len(plan.get('sub_tasks', []))}")
        sections.append(f"")
        sections.append("---")
        sections.append("")

        # Executive summary
        sections.append("## Executive Summary")
        sections.append("")
        sections.append(
            f"This report analyzes **{topic}** across {len(plan.get('sub_tasks', []))} "
            f"research dimensions, drawing from {len(findings)} sources. "
            f"The research was conducted at '{depth}' depth level."
        )
        sections.append("")

        # Findings by sub-task
        for task in plan.get("sub_tasks", []):
            task_title = task.get("title", "Untitled")
            task_findings = task.get("findings", [])

            sections.append(f"## {task_title}")
            sections.append("")

            if task_findings:
                for f in task_findings:
                    title = f.get("title", "")
                    url = f.get("url", "")
                    body = f.get("body", "")

                    sections.append(f"### {title}")
                    if url:
                        sections.append(f"**Source:** [{url}]({url})")
                    sections.append(f"")
                    sections.append(f"{body}")
                    sections.append("")
            else:
                sections.append("*No specific findings for this sub-task.*")
                sections.append("")

        # Conclusion
        sections.append("## Conclusion")
        sections.append("")
        sections.append(
            f"This research covered {len(plan.get('sub_tasks', []))} aspects of "
            f"'{topic}', examining {len(findings)} sources. "
            f"The findings provide a {'comprehensive' if depth == 'deep' else 'structured'} "
            f"overview of the current landscape."
        )
        sections.append("")

        # Methodology
        sections.append("## Methodology")
        sections.append("")
        sections.append("This report was generated using the DeerFlow Research Agent pipeline:")
        sections.append("1. **Planning** — Topic decomposition into sub-tasks")
        sections.append("2. **Searching** — Web search and information gathering")
        sections.append("3. **Analysis** — Synthesis and report generation")
        sections.append("")
        sections.append("---")
        sections.append(f"*Generated by DeerFlow Research Agent on {date_str}*")

        markdown = "\n".join(sections)

        return {
            "topic": topic,
            "depth": depth,
            "summary": f"Research report on '{topic}' with {len(findings)} sources across {len(plan.get('sub_tasks', []))} dimensions.",
            "markdown": markdown,
            "findings_count": len(findings),
            "sub_tasks_count": len(plan.get("sub_tasks", [])),
            "generated_at": datetime.now().isoformat(),
        }
